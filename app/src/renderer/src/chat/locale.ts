export function isLocale(value: unknown): value is Locale {
  return value === 'ar' || value === 'en'
}

/** Fill {placeholders} in a template. Unknown params stay verbatim. */
export function fill(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

export function translate(
  locale: Locale,
  key: StringKey,
  params?: Record<string, string | number>
): string {
  const table = locale === 'ar' ? ar : en
  return fill(table[key], params)
}

/**
 * Simplified plural: one (n==1) / two (n==2) / many (else), with Arabic
 * dual support. `forms` carries the per-count templates; {n} is filled.
 */
export function plural(
  locale: Locale,
  n: number,
  forms: { one: string; two: string; many: string }
): string {
  if (n === 1) return fill(forms.one, { n })
  if (locale === 'ar' && n === 2) return fill(forms.two, { n })
  return fill(forms.many, { n })
}

/** Relative "time ago" for sidebar/changes rows. Falls back to a date. */
export function relativeTime(locale: Locale, iso: string): string {
  const then = new Date(iso).getTime()
  if (Number.isNaN(then)) return ''
  const seconds = Math.round((Date.now() - then) / 1000)
  if (seconds < 60) return translate(locale, 'sidebar.justNow')
  const minutes = Math.floor(seconds / 60)
  if (minutes < 60)
    return locale === 'ar' ? `منذ {n} د`.replace('{n}', String(minutes)) : `${minutes}m ago`
  const hours = Math.floor(minutes / 60)
  if (hours < 24)
    return locale === 'ar' ? `منذ {n} س`.replace('{n}', String(hours)) : `${hours}h ago`
  const days = Math.floor(hours / 24)
  if (days < 7) return locale === 'ar' ? `منذ {n} يوم`.replace('{n}', String(days)) : `${days}d ago`
  try {
    return new Date(iso).toLocaleDateString(locale === 'ar' ? 'ar' : undefined)
  } catch {
    return new Date(iso).toLocaleDateString()
  }
}
